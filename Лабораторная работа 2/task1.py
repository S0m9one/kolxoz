money_capital = 20000  # Подушка безопасности
salary = 5000  # Ежемесячная зарплата
spend = 6000  # Траты за первый месяц
increase = 0.05  # Ежемесячный рост цен

# TODO Посчитайте количество  месяцев, которое можно протянуть без долгов
month = 0  # Количество месяцев, которое можно протянуть без долгов

while True:
    # Бюджет текущего месяца = зарплата + подушка безопасности
    budget = salary + money_capital
    
    # Если траты превышают бюджет, нельзя протянуть этот месяц
    if spend > budget:
        break
    
    # Можем протянуть этот месяц
    month += 1
    
    # После трат остаётся: бюджет - траты = money_capital + salary - spend
    money_capital = money_capital + salary - spend
    
    # Увеличиваем траты на следующий месяц
    spend = spend * (1 + increase)





print("Количество месяцев, которое можно протянуть без долгов:", month)
